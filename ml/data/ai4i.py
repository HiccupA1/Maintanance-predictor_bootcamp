"""AI4I 2020 Predictive Maintenance dataset: pinned download and validation.

Source: UCI Machine Learning Repository, dataset 601 (CC BY 4.0).
Matzka, S. (2020). Explainable Artificial Intelligence for Predictive
Maintenance Applications. https://doi.org/10.24432/C5HS5C

The data is synthetic. Failure labels are generated by fixed rules on the
process variables, so models trained on it learn those rules. Its metrics
are not an estimate of field performance (see the model card).
"""

from __future__ import annotations

import hashlib
import io
import urllib.request
import zipfile
from pathlib import Path

import pandas as pd

from ml.config import DATA_DIR

URL = (
    "https://archive.ics.uci.edu/static/public/601/"
    "ai4i+2020+predictive+maintenance+dataset.zip"
)
CSV_NAME = "ai4i2020.csv"
CSV_SHA256 = "dc6630cd9b1f0f853922fad78a1b6436570d3f1ec863f1dd5c4340ac56bc8a8e"

COLUMNS = {
    "UDI": "int64",
    "Product ID": "object",
    "Type": "object",
    "Air temperature [K]": "float64",
    "Process temperature [K]": "float64",
    "Rotational speed [rpm]": "int64",
    "Torque [Nm]": "float64",
    "Tool wear [min]": "int64",
    "Machine failure": "int64",
    "TWF": "int64",
    "HDF": "int64",
    "PWF": "int64",
    "OSF": "int64",
    "RNF": "int64",
}
TARGET = "Machine failure"
# Per-mode flags are part of the label, not inputs (leakage if used).
MODE_COLUMNS = ["TWF", "HDF", "PWF", "OSF", "RNF"]


def _sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def download(data_dir: Path = DATA_DIR) -> Path:
    """Download the CSV once and verify its pinned checksum."""
    path = data_dir / CSV_NAME
    if not path.exists():
        data_dir.mkdir(parents=True, exist_ok=True)
        with urllib.request.urlopen(URL, timeout=60) as resp:  # noqa: S310
            archive = zipfile.ZipFile(io.BytesIO(resp.read()))
        path.write_bytes(archive.read(CSV_NAME))
    actual = _sha256(path)
    if actual != CSV_SHA256:
        raise ValueError(
            f"{path} checksum {actual} does not match the pinned "
            f"{CSV_SHA256}; refusing to train on unverified data."
        )
    return path


def validate(df: pd.DataFrame) -> pd.DataFrame:
    """Fail fast on schema or value problems."""
    missing = set(COLUMNS) - set(df.columns)
    if missing:
        raise ValueError(f"missing columns: {sorted(missing)}")
    for column, dtype in COLUMNS.items():
        if str(df[column].dtype) != dtype and not (
            dtype == "object" and pd.api.types.is_string_dtype(df[column])
        ):
            raise ValueError(
                f"{column}: expected {dtype}, got {df[column].dtype}"
            )
    if df[list(COLUMNS)].isna().any().any():
        raise ValueError("dataset contains nulls")
    if not set(df["Type"]).issubset({"L", "M", "H"}):
        raise ValueError("unexpected product Type values")
    if not set(df[TARGET]).issubset({0, 1}):
        raise ValueError("target must be binary")
    if df["UDI"].duplicated().any():
        raise ValueError("duplicate UDI rows")
    return df


def load(data_dir: Path = DATA_DIR) -> pd.DataFrame:
    """Download (if needed), verify and validate the dataset."""
    return validate(pd.read_csv(download(data_dir)))
